export const raidTiers: RaidTier[] = [midnightSeason2, midnightSeason1];
export const defaultRaidTierSlug = midnightSeason2.slug;

export const getRaidBosses = (tier: RaidTier) =>
  tier.instances.flatMap((instance) => instance.bosses).sort((a, b) => a.order - b.order);

export const getProgressionTotal = (tier: RaidTier, difficulty: "normal" | "heroic" | "mythic") => {
  const bosses = getRaidBosses(tier);
  const key = ({
    normal: "normalDefeated",
    heroic: "heroicDefeated",
    mythic: "mythicDefeated",
  } as const)[difficulty];
  return { defeated: bosses.filter((boss) => boss[key]).length, total: bosses.length };
};
